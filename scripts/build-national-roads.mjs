// Builds src/lib/national-roads.ts: DPWH national roads around the jeepney routes, for the tricycle highway surcharge.
// Run with `npm run national-roads` (Node 22.18+ for the .ts import). Data © OpenStreetMap contributors, ODbL.

import { writeFileSync } from "node:fs"
import { routes } from "../src/lib/routes.ts"

const OVERPASS_URLS = ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter"]
const SIMPLIFY_M = 15

const pts = routes.flatMap((r) => r.geometry.coordinates)
const pad = 0.02
const bbox = [
  Math.min(...pts.map((p) => p[1])) - pad,
  Math.min(...pts.map((p) => p[0])) - pad,
  Math.max(...pts.map((p) => p[1])) + pad,
  Math.max(...pts.map((p) => p[0])) + pad,
].map((n) => n.toFixed(4))

// PH mappers tag DPWH roads with designation=national_*; trunk and numeric route refs (J. P. Laurel is 916-5) catch the untagged ones.
const box = bbox.join(",")
const query = `[out:json][timeout:180];(way[highway][designation~"^national_"](${box});way[highway=trunk](${box});way[highway~"^(primary|secondary|tertiary)$"][ref~"^[0-9]"](${box}););out geom qt;`
console.log("Fetching national roads from Overpass…")
let response
for (const url of OVERPASS_URLS) {
  response = await fetch(url, { method: "POST", body: new URLSearchParams({ data: query }), headers: { "User-Agent": "davguides-national-roads" } }).catch(
    (error) => (console.log(`${url} failed: ${error.message}`), undefined),
  )
  if (response?.ok) break
  if (response) console.log(`${url} answered HTTP ${response.status}`)
}
if (!response?.ok) throw new Error(`Overpass failed: ${response ? `HTTP ${response.status}` : "no response"}`)
const { elements } = await response.json()

function offsetM(p, a, b) {
  const k = 111320
  const cos = Math.cos((a[0] * Math.PI) / 180)
  const [ax, ay, bx, by, px, py] = [a[1] * k * cos, a[0] * k, b[1] * k * cos, b[0] * k, p[1] * k * cos, p[0] * k]
  const [dx, dy] = [bx - ax, by - ay]
  const t = dx || dy ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy))) : 0
  return Math.hypot(px - ax - t * dx, py - ay - t * dy)
}

function simplify(line) {
  if (line.length < 3) return line
  const [a, b] = [line[0], line.at(-1)]
  let [worst, worstM] = [0, 0]
  for (let i = 1; i < line.length - 1; i++) {
    const m = offsetM(line[i], a, b)
    if (m > worstM) [worst, worstM] = [i, m]
  }
  if (worstM <= SIMPLIFY_M) return [a, b]
  return [...simplify(line.slice(0, worst + 1)).slice(0, -1), ...simplify(line.slice(worst))]
}

// One id per named road, so both sides of a divided highway count as a single crossing.
const roadIds = new Map()
const roadId = (e) => {
  const key = e.tags.name ?? e.tags.ref ?? `way/${e.id}`
  if (!roadIds.has(key)) roadIds.set(key, roadIds.size)
  return roadIds.get(key)
}

// Ramps and links aren't the highway itself.
const lines = elements
  .filter((e) => e.type === "way" && e.geometry && !e.tags.highway.endsWith("_link"))
  .map((e) => [roadId(e), simplify(e.geometry.map((g) => [+g.lat.toFixed(5), +g.lon.toFixed(5)]))])

const body = `// Generated by scripts/build-national-roads.mjs. Data © OpenStreetMap contributors, ODbL.\n// [road id, [lat, lng] polyline] for DPWH national roads. Load with a dynamic import only.\n\nexport const nationalRoads: [number, [number, number][]][] = ${JSON.stringify(lines)}\n`
writeFileSync(new URL("../src/lib/national-roads.ts", import.meta.url), body)
console.log(`Wrote src/lib/national-roads.ts: ${roadIds.size} roads, ${lines.length} ways, ${lines.reduce((s, l) => s + l[1].length, 0)} points, ${(body.length / 1024).toFixed(0)} KB`)
